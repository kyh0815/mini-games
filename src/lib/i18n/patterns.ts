/** 서버가 값을 끼워 넣어 만든 문장을 일본어로 옮기는 규칙 */
export const JA_PATTERNS: [RegExp, (match: RegExpExecArray) => string][] = [
  [/^(\d+)명 이상 모여야 시작할 수 있습니다\.$/, (m) => `${m[1]}人以上集まると始められます。`],
  [/^방이 가득 찼습니다\. \(최대 (\d+)명\)$/, (m) => `ルームが満員です。(最大${m[1]}人)`],
  [/^'(.+)'\(으\)로 시작해야 합니다\.$/, (m) => `「${m[1].replaceAll("' 또는 '", "」か「")}」で始めてください。`],
  [/^(\d+)칸을 모두 채워 주세요\.$/, (m) => `${m[1]}マスをすべて埋めてください。`],
  [/^서로 다른 숫자 (\d+)개를 입력해 주세요\.$/, (m) => `異なる数字を${m[1]}個入力してください。`],
  [/^공지는 (\d+)자까지 쓸 수 있습니다\.$/, (m) => `お知らせは${m[1]}文字までです。`],
  [/^명중률 (\d+)%$/, (m) => `命中率 ${m[1]}%`],
  [/^(\d+)번 뒤집음$/, (m) => `${m[1]}回めくり`],
  [/^최고 (\d+)ms$/, (m) => `最速 ${m[1]}ms`],
];
